-- 37 — Nome, tipo e cidade das filiais, tratados
--
-- Rode depois do 36.
--
-- AS TRÊS COLUNAS QUE A FICHA MOSTRA
-- ----------------------------------
--   NOME   — exatamente o rótulo do PDF do ProUni/MEC, tirando SÓ o prefixo
--            "MEGA POLO ". Ele já aparece no tipo; repetir no nome é ruído.
--            Tudo o mais fica como o MEC escreveu, inclusive as
--            inconsistências ("ALEGRETE-RS" sem espaços, "Campinas-(Bonfim)").
--            O nome é o que o analista reconhece; não é hora de "arrumar".
--
--   TIPO   — "Mega Polo" para quem tinha o prefixo, "Polo" para todo o resto.
--
--   CIDADE — a cidade de verdade, sem o bairro e sem a UF. Toda filial fica
--            numa cidade, mas uma cidade pode ter VÁRIAS filiais: Brasília tem
--            nove (Águas Claras, Ceilândia, Gama, Guará, Samambaia, Santa
--            Maria, Sol Nascente, Taguatinga, Ceilândia Norte) e continua
--            sendo uma cidade só. Por isso o parêntese sai: ele é a unidade
--            dentro da cidade, não outra cidade.
--
-- A 34 tinha guardado o nome já sem a UF e a cidade com o "MEGA POLO" colado
-- (esta última consertada na 35). Aqui as três colunas são refeitas de uma vez,
-- a partir do rótulo original do PDF.
--
-- ⚠️ ISTO RECLASSIFICA AS DUAS SEDES. `CAMPUS GETÚLIO` e `CAMPUS SANEPAR`
-- estavam como tipo "Sede", e passam a "Polo" — a regra combinada é "quem não
-- tem MEGA POLO no nome é Polo", e elas estão na mesma lista do MEC. A cidade
-- delas (Paranavaí/PR) é preservada, porque o rótulo do PDF não traz UF para
-- elas e `coalesce` não deixa o nulo derivado apagar o que já estava certo.
-- ============================================================================

