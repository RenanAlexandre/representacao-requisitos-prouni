-- lugar da UF, então a extração automática não acha nem cidade nem estado. O
-- registro fica logo abaixo de "CAMPINAS (CIDADE UNIVERSITÁRIA) - SP" na
-- listagem alfabética do MEC — é Campinas, SP. Está aqui, à mão e assumido,
-- em vez de escondido dentro da regra geral.
-- ---------------------------------------------------------------------------
update polos set cidade = 'Campinas', uf = 'SP'
 where codigo_sispro = '1128612' and cidade is null;


-- ---------------------------------------------------------------------------
-- Conferência
-- ---------------------------------------------------------------------------
do $blk$
declare
  v_faltando int;
  v_mega     int;
  v_sujo     int;
  v_brasilia int;
  v_sedes    int;
  r          record;
begin
  select count(*) into v_faltando
    from filiais_pdf f left join polos p on p.codigo_sispro = f.codigo
   where p.id is null;
  if v_faltando > 0 then
    raise exception '% filial(is) do PDF não existem em polos', v_faltando;
  end if;

  -- Nenhum nome pode ter sobrado com o prefixo, e nenhuma cidade com bairro.
  select count(*) into v_sujo from polos
   where nome ~* '^MEGA\s+POLO' or cidade ~ '\(' or cidade ~* '^MEGA';
  if v_sujo > 0 then
    raise exception '% filial(is) com nome ou cidade mal tratados', v_sujo;
  end if;

  select count(*) into v_mega from polos where tipo = 'Mega Polo';
  select count(*) into v_sedes from polos where tipo not in ('Polo', 'Mega Polo');
  if v_sedes > 0 then
    raise exception '% filial(is) com tipo fora de Polo/Mega Polo', v_sedes;
  end if;

  -- Brasília é o caso que o usuário citou: várias filiais, uma cidade só.
  select count(distinct cidade || '/' || uf) into v_brasilia
    from polos where cidade ilike 'BRAS_LIA';
  if v_brasilia <> 1 then
    raise exception 'Brasília ficou com % cidades distintas', v_brasilia;
  end if;

  raise notice '938 filiais tratadas | % mega polos', v_mega;
  for r in
    select nome, tipo, cidade, uf from polos where cidade ilike 'BRAS_LIA' order by nome limit 4
  loop
    raise notice '  % | % | % - %', rpad(r.nome, 34), rpad(r.tipo, 9), r.cidade, r.uf;
  end loop;
end;
$blk$;
